import { test, expect } from '@playwright/test';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { createServer } from '../../server/api';
import { paymentDependencies } from '../fixtures';

test('Flow scenarios save, copy, restore drafts, detect stale mocks, and restore reports',async({page},info)=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'mockingbird-regression-ui-')),project=path.join(temp,'payment-service');
  await fs.cp('examples/payment-service',project,{recursive:true,filter:s=>!s.includes('/target')&&!s.includes('/.mockingbird')});
  const service=await createServer({root:process.cwd(),dataDir:path.join(temp,'data')},0),errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto(`http://127.0.0.1:${service.port}`);
    await page.getByRole('button',{name:'打开新项目',exact:true}).click();
    await page.getByPlaceholder('/path/to/your/java-project').fill(project);
    await page.getByRole('button',{name:'打开并索引',exact:true}).click();
    await expect(page.locator('.project-root')).toContainText('payment-service');
    const bench=[...service.projects.workbenches.values()][0],wf=await bench.analyzeEntry(bench.workspace.project!.entries.find(e=>e.path.endsWith('/create'))!.id);
    for(const dep of paymentDependencies(bench.index!))await bench.saveDependency(wf.id,dep);
    await bench.setRules(bench.generate());
    await page.locator('.api-card').filter({hasText:'/api/payment/create'}).click();
    await page.getByRole('button',{name:'场景集',exact:true}).click();
    await expect(page.getByRole('button',{name:'运行回归 (0)',exact:true})).toBeDisabled();
    await page.getByRole('button',{name:'新建场景',exact:true}).click();
    await page.getByLabel('场景名称',{exact:true}).fill('成功支付');
    await page.getByLabel('场景请求 Body',{exact:true}).fill('{"userId":"u_001","sku":"sku_001","quantity":1,"amount":128}');
    await page.getByLabel('场景响应断言',{exact:true}).fill('{"/status":"COMPLETED"}');
    await page.getByLabel('调用次数 Bank API',{exact:true}).fill('0');
    await page.getByRole('button',{name:'保存场景',exact:true}).click();
    await expect.poll(()=>bench.workspace.flowScenarios?.length).toBe(1);
    expect(bench.workspace.flowScenarios![0].mocks.find(m=>m.dependencyId===bench.activeWorkflow().dependencies.find(d=>d.name==='Bank API')!.id)!.calls).toBe(0);
    await page.getByRole('button',{name:'复制场景 成功支付',exact:true}).click();
    await expect(page.getByLabel('场景名称',{exact:true})).toHaveValue('成功支付 · 副本');
    await page.getByLabel('场景名称',{exact:true}).fill('未保存草稿');
    await page.reload();
    await expect(page.getByLabel('场景名称',{exact:true})).toHaveValue('未保存草稿');
    await page.getByRole('button',{name:'保存场景',exact:true}).click();
    await expect.poll(()=>bench.workspace.flowScenarios?.length).toBe(2);
    await page.getByRole('button',{name:'删除场景 未保存草稿',exact:true}).click();
    await expect.poll(()=>bench.workspace.flowScenarios?.length).toBe(1);
    await expect(page.locator('.scenario-row')).toHaveCount(1);
    const changed=structuredClone(bench.workspace.rules);changed[0].delay=1;await bench.setRules(changed);
    await expect(page.locator('.scenario-row')).toContainText('待复核');
    await page.getByRole('button',{name:'运行回归 (1)',exact:true}).click();
    await expect(page.locator('.regression-report')).toContainText('Mock 内容已变化');
    await expect(page.locator('.regression-result summary')).toContainText('阻塞');
    bench.regression.state=undefined;
    await page.reload();
    await expect(page.locator('.regression-report')).toContainText('Mock 内容已变化');
    await page.locator('.scenario-name').filter({hasText:'成功支付'}).click();
    await page.setViewportSize({width:1800,height:1100});
    await page.locator('.project-container:not([hidden])').getByTitle('收起 AI 面板',{exact:true}).click();
    await page.getByLabel('调用次数 Bank API',{exact:true}).fill('1');
    await page.screenshot({path:info.outputPath('flow-scenarios.png')});
    await page.getByRole('button',{name:'收起',exact:true}).click();
    await page.screenshot({path:info.outputPath('flow-regression-report.png')});
    await page.locator('.scenario-name').filter({hasText:'成功支付'}).click();
    // A malformed JSON draft must never update the saved scenario.
    await page.getByLabel('场景响应断言',{exact:true}).fill('{broken');
    await page.getByRole('button',{name:'保存场景',exact:true}).click();
    await expect(page.locator('.scenarios-view [role=alert]')).toBeVisible();
    expect(bench.workspace.flowScenarios![0].expected.fields).toEqual({'/status':'COMPLETED'});
    await page.getByRole('button',{name:'路由配置',exact:true}).click();
    await page.getByRole('button',{name:'验证入口 API',exact:true}).click();
    await page.getByLabel('请求路径',{exact:true}).fill('/api/payment/create?scenario=checkout');
    await page.getByRole('button',{name:'保存为 Flow 场景',exact:true}).click();
    await expect(page.getByLabel('场景请求路径',{exact:true})).toHaveValue('/api/payment/create?scenario=checkout');
    await expect(page.getByLabel('场景名称',{exact:true})).toHaveValue('新场景');
    await page.getByLabel('场景名称',{exact:true}).fill('从入口请求保存');
    await page.getByRole('button',{name:'保存场景',exact:true}).click();
    await expect.poll(()=>bench.workspace.flowScenarios?.length).toBe(2);
    expect(errors).toEqual([]);
  }finally{await service.close();await fs.rm(temp,{recursive:true,force:true});}
});
