import { spawn, type ChildProcess } from 'node:child_process';
import { once } from 'node:events';
import net from 'node:net';
import type { Workspace, Dependency, LaunchStatus } from '../shared/types';
import { assertPort, redact, terminate } from './runtime';
import { atomicWrite } from './storage';
import { exists } from './analyzer';
import { projectLaunchCommand } from './launch';

export interface RoutePreview { config:string; changes:{key:string;before:string;after:string}[]; unsupported:{name:string;reason:string}[]; command:string }
export async function routePreview(ws:Workspace,port:number,launchPort=18080):Promise<RoutePreview>{
  if(!ws.project)throw new Error('请先导入项目');
  const dependencies=ws.workflows.flatMap(w=>w.dependencies),changes:RoutePreview['changes']=[],unsupported:RoutePreview['unsupported']=[];
  const keys=new Map<string,Dependency[]>();
  for(const d of dependencies){if(d.configKey){const group=keys.get(d.configKey)||[];group.push(d);keys.set(d.configKey,group);}else if(d.route==='mock')unsupported.push({name:d.name,reason:'未发现可覆盖的配置项；硬编码 URL 不支持自动路由'});}
  for(const[key,deps]of keys){
    if(!deps.some(d=>d.route==='mock'))continue;
    if(deps.some(d=>d.route==='real'))throw new Error(`配置项 ${key} 被多个依赖共享，必须一起切换为 Mock 或 Real`);
    const dep=deps[0];if(dep.status==='unresolved'||!dep.originalBase){unsupported.push({name:dep.name,reason:'URL 配置未解析'});continue;}
    if(!/^[\w.-]+$/.test(key))throw new Error('配置键含有不支持的字符');
    const original=new URL(dep.originalBase);const after=`http://127.0.0.1:${port}${original.pathname==='/'?'':original.pathname}`;
    changes.push({key,before:dep.originalBase,after});
  }
  const config='# Generated by Mockingbird. Original project configuration is unchanged.\n'+changes.map(c=>c.key+'='+c.after).join('\n')+'\n';
  const {command}=await projectLaunchCommand(ws,launchPort);
  return{config,changes,unsupported,command};
}
export async function writeRoutes(ws:Workspace,port:number){
  const preview=await routePreview(ws,port);if(preview.unsupported.length)throw new Error(preview.unsupported.map(x=>x.name+': '+x.reason).join('\n'));
  if(ws.project)await atomicWrite(path.join(ws.project.path,'.mockingbird/routes.properties'),preview.config);
  return preview;
}
export class ProjectLauncher{
  state:LaunchStatus={status:'stopped',port:18080,logs:[]};child?:ChildProcess;
  constructor(private changed:()=>void){}
  async start(ws:Workspace,port=18080){
    if(!ws.project)throw new Error('请先导入项目');if(this.child)throw new Error('项目已启动，请先停止');await assertPort(port);
    const {executable,args,cwd:root,location,command,env}=await projectLaunchCommand(ws,port);
    if(!await exists(location))throw new Error('请先预览并应用路由配置');
    this.state={status:'starting',port,logs:[`$ ${command}`],config:location,stale:false};this.changed();
    const child=spawn(executable,args,{cwd:root,detached:process.platform!=='win32',stdio:['ignore','pipe','pipe'],env});this.child=child;
    const log=(chunk:Buffer)=>{this.state.logs.push(redact(chunk.toString()));this.state.logs=this.state.logs.slice(-500);this.changed();};
    child.stdout?.on('data',log);child.stderr?.on('data',log);
    child.on('error',e=>{this.child=undefined;this.state.status='failed';this.state.error=e.message;this.changed();});
    child.on('close',code=>{if(this.child===child){this.child=undefined;this.state.status='failed';this.state.error=`项目退出（${code}），请检查 Terminal 日志`;this.changed();}});
    const timer=setInterval(()=>{
      if(this.child!==child){clearInterval(timer);return;}
      const socket=net.connect(port,'127.0.0.1');socket.on('connect',()=>{socket.destroy();this.state.status='running';this.changed();clearInterval(timer);});socket.on('error',()=>socket.destroy());socket.setTimeout(500,()=>socket.destroy());
    },1000);timer.unref();child.once('close',()=>clearInterval(timer));
    const timeout=setTimeout(()=>{if(this.child===child&&this.state.status==='starting'){terminate(child);this.state.status='failed';this.state.error='项目启动超过 3 分钟，已停止，请检查构建日志';this.changed();}},180000);timeout.unref();child.once('close',()=>clearTimeout(timeout));
  }
  async stop(){const c=this.child;this.child=undefined;this.state.status='stopped';this.state.error=undefined;this.changed();if(c){const done=once(c,'close').catch(()=>{});terminate(c);await Promise.race([done,new Promise(r=>setTimeout(r,3500))]);}}
}
